"""Typed sales data; customer terms are not accounting entries or production costs."""
from datetime import date
from typing import Annotated, Literal

from fastapi import HTTPException
from pydantic import BaseModel, ConfigDict, Field, HttpUrl, model_validator
from sqlalchemy import func, select
from sqlalchemy.orm import aliased

from app.crm.models import CRMEntity

Temperature = Literal['hot', 'warm', 'cold']
Money = Annotated[float, Field(ge=0, le=1e12, allow_inf_nan=False)]


class SalesModel(BaseModel):
    model_config = ConfigDict(extra='forbid')


class CustomerProfile(SalesModel):
    last_name: str = Field('', max_length=200)
    first_name: str = Field('', max_length=200)
    middle_name: str = Field('', max_length=200)
    gender: Literal['male', 'female'] | None = None
    phone_2: str = Field('', max_length=100)
    phone_3: str = Field('', max_length=100)
    source_label: str = Field('', max_length=1000)
    deal_timeframe: str = Field('', max_length=500)
    birth_date: date | None = None
    marital_status: str = Field('', max_length=200)
    marriage_date: date | None = None
    children_birth_dates: list[date] = Field(default_factory=list, max_length=50)
    city: str = Field('', max_length=300)
    temperature: Temperature | None = None


class CustomerNeeds(SalesModel):
    purchase_goal: Literal['living', 'renting'] | None = None
    construction_city: str = Field('', max_length=300)
    property_type: Literal['barn', 'flat', 'undecided'] | None = None
    rooms: int | None = Field(None, ge=0, le=100)
    finishing: Literal['warm_shell', 'eco', 'standard', 'premium'] | None = None
    extras: list[Literal['sauna', 'hot_tub', 'utility_building']] = Field(default_factory=list, max_length=3)


class PurchaseTerms(SalesModel):
    # Budget remains DealData.amount, the existing source of kanban budgets.
    payment_form: Literal['cash', 'mortgage', 'installments', 'trade_in'] | None = None
    initial_payment: Money | None = None
    mortgage_approved: bool | None = None


class SaleTerms(SalesModel):
    object_url: HttpUrl | None = None
    final_customer_price: Money | None = None
    final_payment_timeframe: str = Field('', max_length=500)
    partner_deal: bool | None = None
    # The owner has not chosen an enum; preserve literal commercial wording.
    payment_status: str = Field('', max_length=300)


class AgencyMember(SalesModel):
    contact_id: int = Field(ge=1)
    roles: list[Literal['owner', 'decision_maker', 'marketer', 'agent']] = Field(min_length=1, max_length=4)


class AgencyProfile(SalesModel):
    legal_status: Literal['ooo', 'ip', 'self_employed'] | None = None
    members: list[AgencyMember] = Field(default_factory=list, max_length=100)

    @model_validator(mode='after')
    def unique_contacts(self):
        if len({member.contact_id for member in self.members}) != len(self.members):
            raise ValueError('Укажите все роли одного контакта в одной строке')
        return self


class AgencyReferral(SalesModel):
    agency_id: int = Field(ge=1)
    agent_contact_id: int = Field(ge=1)
    # Always generated by the server on selection; retained when names change.
    agency_name: str = Field('', max_length=1000)
    agent_name: str = Field('', max_length=1000)
    agent_phone: str = Field('', max_length=100)


def merge_sales_patch(previous, patch):
    merged = {**previous, **patch}
    for field in ('customer', 'needs', 'purchase_terms', 'sale_terms', 'agency_profile'):
        if isinstance(previous.get(field), dict) and isinstance(patch.get(field), dict):
            merged[field] = {**previous[field], **patch[field]}
    return merged


def _agency(db, agency_id, *, eligible=False):
    agency = db.get(CRMEntity, agency_id)
    if not agency or agency.kind != 'deal' or agency.archived:
        raise HTTPException(422, 'Выберите действующую карточку агентства')
    pipeline = db.get(CRMEntity, agency.payload.get('pipeline_id'))
    if not pipeline or pipeline.kind != 'pipeline' or pipeline.archived or pipeline.payload.get('purpose') != 'agency':
        raise HTTPException(422, 'Карточка не относится к настроенной воронке агентств')
    if eligible:
        stage = db.get(CRMEntity, agency.payload.get('stage_id'))
        if (not stage or stage.kind != 'stage' or stage.archived
                or stage.payload.get('pipeline_id') != pipeline.id
                or stage.payload.get('agency_source_eligible') is not True):
            raise HTTPException(422, 'Агентство ещё не подключено к партнёрскому каналу')
    return agency


def validate_sales_fields(db, kind, data, previous=None):
    previous = previous or {}
    if kind == 'deal':
        primary = data.get('primary_contact_id')
        if primary is not None and primary not in data['contact_ids']:
            raise HTTPException(422, 'Основной контакт должен быть связан со сделкой')
        profile = data.get('agency_profile')
        if profile is not None:
            pipeline = db.get(CRMEntity, data['pipeline_id'])
            if not pipeline or pipeline.payload.get('purpose') != 'agency':
                raise HTTPException(422, 'Реквизиты агентства доступны в воронке агентств')
            for member in profile['members']:
                contact = db.get(CRMEntity, member['contact_id'])
                if (member['contact_id'] not in data['contact_ids'] or not contact or contact.kind != 'contact'):
                    raise HTTPException(422, 'Сотрудник должен быть CRM-контактом этого агентства')
    referral = data.get('referral')
    if referral is not None:
        old = previous.get('referral') or {}
        if all(referral.get(key) == old.get(key) for key in ('agency_id', 'agent_contact_id')):
            # An unrelated edit must not rewrite historical attribution or be
            # blocked when the agency advances, is archived, or removes a contact.
            data['referral'] = old
        else:
            agency = _agency(db, referral['agency_id'], eligible=True)
            agent = db.get(CRMEntity, referral['agent_contact_id'])
            if (not agent or agent.kind != 'contact' or agent.archived
                    or agent.id not in agency.payload.get('contact_ids', [])):
                raise HTTPException(422, 'Выберите сотрудника именно этого агентства')
            data['referral'] = {**referral, 'agency_name': agency.name, 'agent_name': agent.name,
                                'agent_phone': agent.payload.get('phone', '')}
    return data


def agency_sources(db, query='', offset=0, limit=20):
    """Only explicitly configured eligible stages, with no business mutations."""
    pipelines = db.query(CRMEntity).filter_by(kind='pipeline', archived=False).all()
    pids = {row.id for row in pipelines if row.payload.get('purpose') == 'agency'}
    stages = db.query(CRMEntity).filter_by(kind='stage', archived=False).all()
    sids = {row.id for row in stages if row.payload.get('pipeline_id') in pids
            and row.payload.get('agency_source_eligible') is True}
    rows = db.query(CRMEntity).filter(CRMEntity.kind == 'deal', CRMEntity.archived.is_(False),
        CRMEntity.payload['pipeline_id'].as_integer().in_(pids),
        CRMEntity.payload['stage_id'].as_integer().in_(sids)).order_by(CRMEntity.id).all()
    search = query.strip().casefold()
    if search:
        rows = [row for row in rows if search in row.name.casefold()]
    items = []
    for row in rows[offset:offset + limit]:
        contacts = db.query(CRMEntity).filter(CRMEntity.kind == 'contact', CRMEntity.archived.is_(False),
            CRMEntity.id.in_(row.payload.get('contact_ids', []))).order_by(CRMEntity.id).all()
        items.append({'id': row.id, 'name': row.name, 'contacts': [
            {'id': contact.id, 'name': contact.name, 'phone': contact.payload.get('phone', '')} for contact in contacts]})
    return {'total': len(rows), 'items': items, 'offset': offset, 'configured': bool(pids and sids)}


def temperature_expression(kind):
    """Contact profile is canonical; deals use an explicit or first linked contact."""
    direct = CRMEntity.payload['customer']['temperature'].as_string()
    if kind not in ('deal', 'inquiry'):
        return direct
    contact = aliased(CRMEntity)
    primary = func.coalesce(CRMEntity.payload['primary_contact_id'].as_integer(),
                            CRMEntity.payload['contact_ids'][0].as_integer())
    if kind == 'inquiry':
        deal = aliased(CRMEntity)
        linked = func.coalesce(CRMEntity.payload['accepted_deal_id'].as_integer(),
                               CRMEntity.payload['deal_id'].as_integer())
        primary = select(func.coalesce(deal.payload['primary_contact_id'].as_integer(),
                                       deal.payload['contact_ids'][0].as_integer())).where(
            deal.kind == 'deal', deal.id == linked).correlate(CRMEntity).scalar_subquery()
    temperature = select(contact.payload['customer']['temperature'].as_string()).where(
        contact.kind == 'contact', contact.id == primary).correlate(CRMEntity).scalar_subquery()
    return func.coalesce(temperature, direct)
